-- 1. Create the `profiles` table
-- This table stores extended information for university students.
-- Each profile is linked directly to an authenticated user in Supabase Auth via `id`.
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    faculty TEXT,
    degree TEXT,
    academic_year TEXT,
    profile_image TEXT DEFAULT 'https://api.dicebear.com/7.x/avataaars/svg?seed=student',
    bio TEXT DEFAULT 'University undergraduate excited to collaborate and share knowledge on UniSkill Hub.',
    skills TEXT DEFAULT 'Web Development, Problem Solving, Communication',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- 3. Security Policies for `profiles` table

-- Policy: Anyone (authenticated or guest) can view student profiles
CREATE POLICY "Public profiles are viewable by everyone" 
ON public.profiles 
FOR SELECT 
USING (true);

-- Policy: An authenticated user can insert their own profile record
CREATE POLICY "Users can insert their own profile" 
ON public.profiles 
FOR INSERT 
WITH CHECK (auth.uid() = id);

-- Policy: An authenticated user can update only their own profile
CREATE POLICY "Users can update own profile" 
ON public.profiles 
FOR UPDATE 
USING (auth.uid() = id);

-- 4. Automatic Profile Trigger (Recommended Supabase Best Practice)
-- Automatically creates a profile entry when a user signs up via Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, email, faculty, degree, academic_year, bio, skills)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', 'Student User'),
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'faculty', 'Faculty of Science'),
        COALESCE(NEW.raw_user_meta_data->>'degree', 'Undergraduate Degree'),
        COALESCE(NEW.raw_user_meta_data->>'academic_year', '1st Year'),
        'Undergraduate student at UniSkill Hub.',
        COALESCE(NEW.raw_user_meta_data->>'skills', 'General Studies')
    )
    ON CONFLICT (id) DO UPDATE SET
        full_name = EXCLUDED.full_name,
        faculty = EXCLUDED.faculty,
        degree = EXCLUDED.degree,
        academic_year = EXCLUDED.academic_year;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger to execute the function on user signup
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

